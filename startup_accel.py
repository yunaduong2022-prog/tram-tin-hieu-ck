"""Locally generated cold-start cache for Streamlit's existing EOD pipeline.

Only read files generated by this code on the same trusted computer.
No network, VNStock, git or edits of canonical market data.
"""
from __future__ import annotations

import ast
import datetime as dt
import hashlib
import os
from pathlib import Path
import pickle
import platform
import sys
import tempfile
import time

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parent
CACHE_DIR = ROOT / 'data' / '.startup_cache'
CACHE_FILE = CACHE_DIR / 'eod_startup_v1.pkl'
VERSION = 'eod-startup-v1'
INPUTS = (
    'data/eod_prices.csv',
    'data/stock_metadata.csv', 'data/shares_outstanding.csv',
    'data/thong_tin_chung.csv', 'data/nhap_tay.csv',
    'app.py', 'engine.py', 'wyckoff.py', 'stock_tabs.py',
    'cap_filter.py', 'fund_guard.py', 'watchlist.py', 'startup_accel.py',
)
# Avoid expensive deserialization on every Streamlit rerun in the same process.
_LAST_KEY = None
_LAST_BUNDLE = None


def _file_signature(path: Path):
    if not path.is_file():
        return [str(path.relative_to(ROOT)), None]
    stat = path.stat()
    return [str(path.relative_to(ROOT)), stat.st_size, stat.st_mtime_ns]


def signature():
    """Invalidates on data or code edits and Python/pandas/numpy version changes."""
    parts = repr((VERSION, platform.python_version(), pd.__version__, np.__version__,
                  [_file_signature(ROOT / p) for p in INPUTS]))
    return hashlib.sha256(parts.encode('utf-8')).hexdigest()


def load_if_valid():
    global _LAST_KEY, _LAST_BUNDLE
    key = signature()
    if key == _LAST_KEY and _LAST_BUNDLE is not None:
        return _LAST_BUNDLE
    _LAST_KEY, _LAST_BUNDLE = None, None
    if not CACHE_FILE.is_file():
        return None
    try:
        # SECURITY: pickle isn't safe with untrusted sources. This is a private,
        # locally created file under data/.startup_cache, never a downloaded cache.
        with CACHE_FILE.open('rb') as f:
            package = pickle.load(f)
        if not isinstance(package, dict) or package.get('signature') != key:
            return None
        result = package.get('bundle')
        if not isinstance(result, dict) or not all(
            k in result for k in ('raw', 'frames', 'wy', 'market', 'screener')
        ):
            return None
        if not isinstance(result['raw'], pd.DataFrame) or not isinstance(result['screener'], pd.DataFrame):
            return None
        if not set(('D', 'W', 'M')).issubset(result['frames']):
            return None
        _LAST_KEY, _LAST_BUNDLE = key, result
        return result
    except (OSError, EOFError, pickle.UnpicklingError, AttributeError, ImportError,
            ValueError, TypeError, KeyError):
        return None


def save(bundle):
    global _LAST_KEY, _LAST_BUNDLE
    if not isinstance(bundle, dict) or not all(k in bundle for k in ('raw', 'frames', 'wy', 'market', 'screener')):
        raise ValueError('Incomplete derived market-data bundle')
    CACHE_DIR.mkdir(parents=True, exist_ok=True)
    key = signature()
    fd, tmp = tempfile.mkstemp(prefix='.startup_', suffix='.tmp', dir=CACHE_DIR)
    try:
        with os.fdopen(fd, 'wb') as f:
            pickle.dump({'signature': key, 'created_at': dt.datetime.now().isoformat(),
                         'bundle': bundle}, f, protocol=pickle.HIGHEST_PROTOCOL)
            f.flush()
            os.fsync(f.fileno())
        os.replace(tmp, CACHE_FILE)
    finally:
        if os.path.exists(tmp):
            os.remove(tmp)
    _LAST_KEY, _LAST_BUNDLE = key, bundle
    return CACHE_FILE


def _extract_app_functions(source):
    """Use the SAME computations as app.py without executing Streamlit UI code.

    The AST is extracted only from the trusted user's local app.py. No remote code.
    """
    import engine as E
    import wyckoff as WYK
    import cap_filter as CF
    import stock_tabs as ST

    wanted = ('apply_manual_overrides', 'market_cap_map', 'drop_small_caps',
              '_slim_f32', 'build_frames', 'wyckoff_table', 'market_cached',
              'screener_cached')
    tree = ast.parse(source)
    funcs = {n.name: n for n in tree.body if isinstance(n, ast.FunctionDef)}
    missing = set(wanted) - set(funcs)
    if missing:
        raise RuntimeError('App functions changed: ' + ', '.join(sorted(missing)))
    ns = {'pd':pd,'np':np,'os':os,'E':E,'WYK':WYK,'CF':CF,'ST':ST,
          'MIN_CAP_BN':CF.MIN_CAP_BN}
    for name in ('W_KEEP', 'DAILY_KEEP', 'KEEP_F64'):
        assignments = [node for node in tree.body if isinstance(node, ast.Assign) and
                       any(isinstance(t,ast.Name) and t.id==name for t in node.targets)]
        if len(assignments)!=1:
            raise RuntimeError('Missing app configuration: '+name)
        ns[name] = ast.literal_eval(assignments[0].value)
    extracted = []
    for name in wanted:
        fn = funcs[name]
        fn.decorator_list = []  # Do not invoke Streamlit cache/UI from preprocessing.
        extracted.append(fn)
    m = ast.fix_missing_locations(ast.Module(body=extracted,type_ignores=[]))
    exec(compile(m, filename='app.py (offline compute functions)', mode='exec'),ns)
    return ns


def warmup(print_fn=print):
    """Generate once outside Streamlit (Windows). Never imports VNStock."""
    import engine as E
    t0 = time.perf_counter()
    current = load_if_valid()
    if current is not None:
        print_fn('PASS: Startup cache already current; no recomputation required')
        return current
    print_fn('BUILD: Loading and filtering EOD (no VNStock requests)',flush=True)
    source = (ROOT / 'app.py').read_text(encoding='utf-8-sig')
    ns = _extract_app_functions(source)
    raw = E.clean_raw(pd.read_csv(ROOT/'data'/'eod_prices.csv',dtype={'Mã':str}))
    raw = ns['drop_small_caps'](E.clean_raw(raw))
    if raw.empty:
        raise RuntimeError('EOD data is empty after filtering; abort cache')
    print_fn('BUILD: Computing D/W/M indicators from full history',flush=True)
    frames = ns['build_frames'](raw, E.ENGINE_VERSION)
    df = frames['D']
    latest_date = df['Ngày'].max()
    latest_df = df.loc[df['Ngày']==latest_date]
    data_key = f'{latest_date:%Y%m%d}-{len(df)}'
    wy_key = f"{data_key}-{float(latest_df['Giá đóng cửa'].sum()):.2f}"
    print_fn('BUILD: Wyckoff and screener (source formulas unchanged)',flush=True)
    wy = ns['wyckoff_table'](df, wy_key)
    market = ns['market_cached'](raw, wy_key)
    mkt, _ = market
    screener = ns['screener_cached'](frames,mkt,wy_key+'|'+E.ENGINE_VERSION)
    if not isinstance(screener,pd.DataFrame) or not len(screener):
        raise RuntimeError('Empty screener; refuse to publish cache')
    # Verify basic invariants before publishing. The canonical EOD CSV is never changed.
    if not all(isinstance(frames[tf],pd.DataFrame) and len(frames[tf]) for tf in ('D','W','M')):
        raise RuntimeError('Invalid derived timeframe frames')
    bundle = {'raw':raw,'frames':frames,'wy':wy,'market':market,'screener':screener}
    path = save(bundle)
    print_fn('PASS: Startup cache built',flush=True)
    print_fn('EOD SYMBOLS:',raw['Mã'].nunique(),'SCREENER ROWS:',len(screener),
             'LATEST:',latest_date.date(),flush=True)
    print_fn('CACHE:',path,'SIZE_MB:',round(path.stat().st_size/1048576,1),flush=True)
    print_fn('PREPROCESS_SECONDS:',round(time.perf_counter()-t0,2),flush=True)
    return bundle


if __name__=='__main__':
    warmup()
